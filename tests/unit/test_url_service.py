@pytest.mark.anyio
async def test_resolve_short_code_expired_raises(mock_db, mock_cache):
    svc = URLService(db=mock_db, cache=mock_cache)
    mock_cache.get_original_url = AsyncMock(return_value=None)

    expired_time = datetime.now(UTC) - timedelta(days=1)
    record = URL(
        id=uuid.uuid4(),
        original_url="https://expired.org",
        short_code="exp1234",
        is_active=True,
        expires_at=expired_time,
    )
    svc.repo.get_by_short_code = AsyncMock(return_value=record)

    with pytest.raises(URLExpiredError):
        await svc.resolve_short_code("exp1234")


